//! `set_hotkey` writes `hypr/trowel.lua` under `$XDG_CONFIG_HOME`. Never reloads Hyprland.

use std::fs;
use std::io;
use std::path::PathBuf;

pub fn write_chord(chord: &str) -> io::Result<Option<String>> {
    write_chord_to(&config_hypr(), chord)
}

pub fn write_chord_to(dir: &std::path::Path, chord: &str) -> io::Result<Option<String>> {
    let conflict = live_conflict(chord);
    fs::create_dir_all(dir)?;
    let path = dir.join("trowel.lua");
    let tmp = path.with_extension("lua.tmp");
    fs::write(&tmp, lua_body(chord, "troweld set_hotkey"))?;
    fs::rename(tmp, path)?;
    Ok(conflict)
}

/// All of `hypr/trowel.lua`: the panel's layer rule, the trowel-app window rules and the bind.
/// `trowel setup` writes it too, so a shortcut changed in Settings keeps the window rules.
pub fn lua_body(chord: &str, generated_by: &str) -> String {
    format!(
        "-- generated by {generated_by}\n\
hl.layer_rule({{\n  match = {{ namespace = \"^trowel-(panel|popup)$\" }},\n  no_anim = true,\n  animation = \"none\",\n  blur = true,\n  ignore_alpha = 0.3,\n}})\n\
-- Quickshell reports class org.quickshell; match the window title.\n\
hl.window_rule({{\n  name = \"trowel-app\",\n  match = {{ title = \"^Trowel$\" }},\n  float = true,\n  size = \"1040 700\",\n}})\n\
hl.window_rule({{\n  name = \"trowel-quicklook\",\n  match = {{ title = \"^Trowel Quick Look$\" }},\n  float = true,\n  size = \"1200 800\",\n}})\n\
o.bind(\"{chord}\", \"Trowel search\", \"omarchy-shell trowel toggle\")\n"
    )
}

fn config_hypr() -> PathBuf {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            let home = std::env::var_os("HOME").unwrap_or_else(|| "/tmp".into());
            PathBuf::from(home).join(".config")
        });
    base.join("hypr")
}

fn live_conflict(chord: &str) -> Option<String> {
    let out = std::process::Command::new("hyprctl")
        .args(["-j", "binds"])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let text = String::from_utf8_lossy(&out.stdout);
    if text.contains(chord) && !text.contains("Trowel search") {
        Some("key already bound".into())
    } else {
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn writes_under_given_dir() {
        let dir = std::env::temp_dir().join(format!(
            "trowel-hypr-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        write_chord_to(&dir, "SUPER + D").unwrap();
        let body = fs::read_to_string(dir.join("trowel.lua")).unwrap();
        assert!(body.contains("o.bind(\"SUPER + D\""));
        // A new shortcut must not drop the window rules `trowel setup` wrote.
        assert!(body.contains("^Trowel$") && body.contains("^Trowel Quick Look$"));
        let _ = fs::remove_dir_all(&dir);
    }
}
