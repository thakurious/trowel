fn split_lines(text: &str) -> Vec<&str> {
    text.split('\n')
        .map(|l| l.strip_suffix('\r').unwrap_or(l))
        .collect()
}

fn line_count(text: &str) -> i32 {
    if text.is_empty() {
        return 0;
    }
    let n = text.bytes().filter(|b| *b == b'\n').count() as i32;
    if text.ends_with('\n') {
        n
    } else {
        n + 1
    }
}

fn dirs_home() -> String {
    std::env::var("HOME").unwrap_or_else(|_| "/".into())
}

fn is_ident_path(name: &str) -> bool {
    let mut rest = name;
    loop {
        let ident = match ident_prefix(rest) {
            Some(i) => i,
            None => return false,
        };
        rest = &rest[ident.len()..];
        if rest.is_empty() {
            return true;
        }
        for sep in ["::", "->", ".", "#"] {
            if let Some(next) = rest.strip_prefix(sep) {
                rest = next;
                break;
            }
            if sep == "#" {
                return false;
            }
        }
    }
}

fn ident_prefix(s: &str) -> Option<&str> {
    let mut chars = s.char_indices();
    let (_, first) = chars.next()?;
    if !(first.is_ascii_alphabetic() || first == '_' || first == '$') {
        return None;
    }
    let mut end = first.len_utf8();
    for (i, c) in chars {
        if c.is_ascii_alphanumeric() || c == '_' || c == '$' {
            end = i + c.len_utf8();
        } else {
            break;
        }
    }
    Some(&s[..end])
}

#[cfg(test)]
mod tests {
    use super::*;

    fn function(name: &str, body: usize, width: usize) -> String {
        let mut s = format!("func {name}() {{\n");
        for i in 1..=body {
            s.push_str(&format!("    let v{i} = \"{}\"\n", "x".repeat(width)));
        }
        s.push_str("}\n");
        s
    }

    #[test]
    fn short_file_is_one_stretch() {
        let pieces = CodeExtractor::lines("import Foundation\n\nfunc a() {}\n", 1800);
        assert_eq!(
            pieces,
            vec![CodePiece {
                text: "import Foundation\n\nfunc a() {}".into(),
                first: 1,
                last: 3
            }]
        );
    }

    #[test]
    fn stretches_end_where_the_code_does() {
        let text = [
            function("first", 22, 40),
            function("second", 22, 40),
            function("third", 22, 40),
        ]
        .join("\n");
        let pieces = CodeExtractor::lines(&text, 1800);
        assert_eq!(pieces.len(), 3);
        assert_eq!(
            pieces
                .iter()
                .map(|p| p.text.lines().next().unwrap())
                .collect::<Vec<_>>(),
            ["func first() {", "func second() {", "func third() {"]
        );
        for piece in &pieces {
            assert!(piece.text.ends_with('}'));
        }
        assert_eq!((pieces[0].first, pieces[0].last), (1, 24));
        assert_eq!((pieces[1].first, pieces[1].last), (26, 49));
    }

    #[test]
    fn a_block_too_long_overlaps_by_two_lines() {
        let pieces = CodeExtractor::lines(&function("huge", 100, 40), 1800);
        assert!(pieces.len() > 2);
        for (piece, next) in pieces.iter().zip(pieces.iter().skip(1)) {
            assert_eq!(next.first, piece.last - 1);
        }
        assert_eq!(pieces.last().unwrap().last, 102);
    }

    #[test]
    fn windows_line_endings_and_blank_edges() {
        let pieces = CodeExtractor::lines("\r\n\r\nfunc a() {\r\n}\r\n\r\n", 1800);
        assert_eq!(
            pieces,
            vec![CodePiece {
                text: "func a() {\n}".into(),
                first: 3,
                last: 4
            }]
        );
    }

    #[test]
    fn left_out_once_read() {
        assert!(
            CodeExtractor::check("// Code generated by protoc. DO NOT EDIT.\nx", true).is_err()
        );
        assert!(CodeExtractor::check(
            "KEY = \"\"\"\n-----BEGIN RSA PRIVATE KEY-----\nabc\n\"\"\"",
            true
        )
        .is_err());
        let minified = format!("!function(){{{} }}();", "var a=1;".repeat(1000));
        assert!(CodeExtractor::check(&minified, true).is_err());
        assert!(CodeExtractor::check(
            "# Notes\n\nDO NOT EDIT the generated files by hand.\n",
            false
        )
        .is_ok());
        assert!(CodeExtractor::check("func a() {}\n", true).is_ok());
    }

    #[test]
    fn code_queries_identifier() {
        assert_eq!(
            CodeLookup::identifier("quantize_row_q8_0_ref").unwrap(),
            ["quantize", "row", "q8", "0", "ref"]
        );
        assert!(CodeLookup::identifier("retry").is_none());
    }
}
