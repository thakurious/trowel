#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodePiece {
    pub text: String,
    pub first: i32,
    pub last: i32,
}

pub struct CodeFile {
    pub pieces: Vec<CodePiece>,
    pub title: String,
    pub repo: Option<String>,
    pub lines: i32,
    pub cells: Option<i32>,
}

pub struct CodeExtractor;

impl CodeExtractor {
    pub const LONGEST_PIECE: usize = 4000;

    pub fn read(url: &Path, options: &IndexOptions) -> Result<CodeFile, ExtractError> {
        let data = fs::read(url).map_err(|err| ExtractError::Unreadable(err.to_string()))?;
        let (repo, title) = Self::place(&url.to_string_lossy());
        let ext = url
            .extension()
            .and_then(|s| s.to_str())
            .unwrap_or("")
            .to_lowercase();
        if ext == "ipynb" {
            let cells = Self::notebook_cells(&data)?;
            let text = cells.join("\n");
            if text.len() as i64 > options.max_code_bytes {
                return Err(ExtractError::LeftOut(format!(
                    "cells over {} MB",
                    options.max_code_bytes >> 20
                )));
            }
            Self::check(&text, true)?;
            return Ok(CodeFile {
                pieces: Self::cells(&cells, options.code_stretch as usize),
                title,
                repo,
                lines: line_count(&text),
                cells: Some(cells.len() as i32),
            });
        }
        if data.iter().take(8000).any(|b| *b == 0) {
            return Err(ExtractError::LeftOut("not text".into()));
        }
        let text = String::from_utf8_lossy(&data).into_owned();
        let source = Rules::SOURCE_EXTENSIONS.iter().any(|e| *e == ext);
        Self::check(&text, source)?;
        Ok(CodeFile {
            pieces: Self::lines(&text, options.code_stretch as usize),
            title,
            repo,
            lines: line_count(&text),
            cells: None,
        })
    }

    pub fn check(text: &str, source: bool) -> Result<(), ExtractError> {
        if text.contains("PRIVATE KEY-----") {
            return Err(ExtractError::LeftOut("holds a private key".into()));
        }
        if !source {
            return Ok(());
        }
        let top = text.chars().take(1000).collect::<String>();
        for mark in [
            "DO NOT EDIT",
            "@generated",
            "Code generated by",
            "Autogenerated by",
            "Generated by the protocol",
        ] {
            if top.contains(mark) {
                return Err(ExtractError::LeftOut(format!(
                    "made by a program (“{mark}”)"
                )));
            }
        }
        let lines = line_count(text).max(1);
        let characters = text.chars().count() as i32;
        if characters / lines > 300 && text.split('\n').any(|l| l.chars().count() > 3000) {
            return Err(ExtractError::LeftOut(format!(
                "minified ({} characters a line)",
                characters / lines
            )));
        }
        Ok(())
    }

    /// `upstream/Sources/DigUpKit/CodeExtractor.swift:77`
    pub fn lines(text: &str, size: usize) -> Vec<CodePiece> {
        let mut lines = split_lines(text);
        if lines.last() == Some(&"") {
            lines.pop();
        }
        let count = lines.len();
        let mut offsets = vec![0usize];
        for line in &lines {
            offsets.push(offsets.last().copied().unwrap() + line.chars().count() + 1);
        }
        let blank = |index: usize| lines[index].chars().all(char::is_whitespace);
        let starts_block = |index: usize| {
            let Some(first) = lines[index].chars().next() else {
                return false;
            };
            if first.is_whitespace() {
                return false;
            }
            let trimmed = lines[index].trim();
            !")}]".contains(first) && !CLOSERS.contains(&trimmed)
        };

        let mut pieces = Vec::new();
        let mut start = 0usize;
        while start < count {
            while start < count && blank(start) {
                start += 1;
            }
            if start >= count {
                break;
            }
            let mut end = start + 1;
            while end < count && offsets[end + 1] - offsets[start] <= size {
                end += 1;
            }
            let mut natural = end >= count;
            if !natural {
                let floor = offsets[start] + size * 2 / 5;
                let last_break = |is_break: &dyn Fn(usize) -> bool| -> Option<usize> {
                    let mut line = end;
                    while line > start + 1 && offsets[line] >= floor {
                        if is_break(line) {
                            return Some(line);
                        }
                        line -= 1;
                    }
                    None
                };
                if let Some(cut) = last_break(&|i| starts_block(i) && blank(i - 1))
                    .or_else(|| last_break(&|i| blank(i - 1) || starts_block(i)))
                {
                    end = cut;
                    natural = true;
                }
            }
            let mut last = end;
            while last > start + 1 && blank(last - 1) {
                last -= 1;
            }
            let mut body = lines[start..last].join("\n");
            if body.chars().count() > Self::LONGEST_PIECE {
                body = body.chars().take(Self::LONGEST_PIECE).collect();
            }
            pieces.push(CodePiece {
                text: body,
                first: start as i32 + 1,
                last: last as i32,
            });
            start = if natural {
                end
            } else {
                end.saturating_sub(2).max(start + 1)
            };
        }
        pieces
    }

    pub fn notebook_cells(data: &[u8]) -> Result<Vec<String>, ExtractError> {
        let notebook: Value = serde_json::from_slice(data)
            .map_err(|_| ExtractError::Unreadable("not a notebook".into()))?;
        let cells = notebook
            .get("cells")
            .cloned()
            .or_else(|| {
                notebook
                    .get("worksheets")
                    .and_then(|w| w.as_array())
                    .and_then(|a| a.first())
                    .and_then(|w| w.get("cells").cloned())
            })
            .and_then(|v| v.as_array().cloned())
            .unwrap_or_default();
        Ok(cells
            .iter()
            .map(|cell| {
                let source = cell.get("source").or_else(|| cell.get("input"));
                match source {
                    Some(Value::Array(lines)) => {
                        lines.iter().filter_map(|v| v.as_str()).collect::<String>()
                    }
                    Some(Value::String(s)) => s.clone(),
                    _ => String::new(),
                }
            })
            .collect())
    }

    pub fn cells(cells: &[String], size: usize) -> Vec<CodePiece> {
        let mut pieces = Vec::new();
        let mut text = String::new();
        let mut first = 0i32;
        let mut last = 0i32;
        let flush = |text: &mut String, first: i32, last: i32, pieces: &mut Vec<CodePiece>| {
            if text.is_empty() {
                return;
            }
            pieces.push(CodePiece {
                text: text.clone(),
                first,
                last,
            });
            text.clear();
        };
        for (index, cell) in cells.iter().enumerate() {
            let body = cell.trim();
            if body.is_empty() {
                continue;
            }
            let number = index as i32 + 1;
            if body.chars().count() > size {
                flush(&mut text, first, last, &mut pieces);
                for piece in Self::lines(body, size) {
                    pieces.push(CodePiece {
                        text: piece.text,
                        first: number,
                        last: number,
                    });
                }
                continue;
            }
            if !text.is_empty() && text.chars().count() + 2 + body.chars().count() > size {
                flush(&mut text, first, last, &mut pieces);
            }
            if text.is_empty() {
                first = number;
                text = body.to_string();
            } else {
                text.push_str("\n\n");
                text.push_str(body);
            }
            last = number;
        }
        flush(&mut text, first, last, &mut pieces);
        pieces
    }

    pub fn place(path: &str) -> (Option<String>, String) {
        let home = dirs_home();
        let mut folder = Path::new(path)
            .parent()
            .unwrap_or(Path::new("/"))
            .to_path_buf();
        let mut repo = None;
        while folder.as_os_str().len() > 1 && folder != Path::new(&home) {
            if folder.join(".git").exists() || Rules::is_project_root(&folder) {
                repo = Some(folder.to_string_lossy().into_owned());
                break;
            }
            match folder.parent() {
                Some(p) => folder = p.to_path_buf(),
                None => break,
            }
        }
        if let Some(repo) = repo.clone() {
            let parent = Path::new(&repo)
                .parent()
                .map(|p| p.to_string_lossy().into_owned())
                .unwrap_or_default();
            let title = path
                .strip_prefix(&parent)
                .unwrap_or(path)
                .trim_start_matches('/')
                .to_string();
            return (Some(repo), title);
        }
        let comps: Vec<_> = Path::new(path)
            .components()
            .filter_map(|c| c.as_os_str().to_str())
            .collect();
        let title = comps
            .iter()
            .rev()
            .take(2)
            .rev()
            .copied()
            .collect::<Vec<_>>()
            .join("/");
        (None, title)
    }

    /// First defining line, else first line of code. `upstream/Sources/DigUpKit/CodeExtractor.swift:130`
    pub fn summary(text: &str) -> String {
        let lines: Vec<String> = text
            .split(['\n', '\r'])
            .map(str::trim)
            .filter(|l| !l.is_empty())
            .map(str::to_string)
            .collect();
        let definition = lines.iter().find(|line| {
            line.split_whitespace()
                .take(4)
                .any(CodeLookup::defines_something)
        });
        let code = lines.iter().find(|line| {
            ![
                "//", "#", "/*", "*", "--", "\"\"\"", "import ", "from ", "#include", "using ",
                "package ", "}", ")", "@",
            ]
            .iter()
            .any(|p| line.starts_with(p))
        });
        let line = definition
            .or(code)
            .or(lines.first())
            .map(String::as_str)
            .unwrap_or("");
        if line.chars().count() > 160 {
            format!("{}…", line.chars().take(160).collect::<String>())
        } else {
            line.to_string()
        }
    }
}

pub struct CodeLookup;

impl CodeLookup {
    pub fn identifier(query: &str) -> Option<Vec<String>> {
        let mut name = query.trim().to_string();
        if name.ends_with("()") {
            name.truncate(name.len() - 2);
        }
        if !is_ident_path(&name) {
            return None;
        }
        let camel = name.chars().skip(1).any(|c| c.is_uppercase())
            && name.chars().any(|c| c.is_lowercase());
        let marked = name
            .chars()
            .any(|c| "_.:#$".contains(c) || c.is_ascii_digit());
        if !camel && !marked {
            return None;
        }
        Some(
            name.to_lowercase()
                .split(|c: char| !c.is_ascii_alphanumeric())
                .filter(|s| !s.is_empty())
                .map(str::to_string)
                .collect(),
        )
    }

    /// One FTS5 phrase so the identifier's words match only side by side, as written.
    /// `upstream/Sources/DigUpKit/CodeExtractor.swift:267`
    pub fn phrase(words: &[String]) -> String {
        format!("\"{}\"", words.join(" "))
    }

    pub fn defines_something(word: &str) -> bool {
        DEFINERS.contains(&word) && !matches!(word, "let" | "var" | "const" | "val")
    }

    /// Where `name` is defined in `text` (stretch whose first line is `first`).
    /// `upstream/Sources/DigUpKit/CodeExtractor.swift:275`
    pub fn definition(name: &str, text: &str, first: i32) -> Option<(i32, i32)> {
        let mut best: Option<(i32, i32)> = None;
        for (offset, line) in split_lines(text).into_iter().enumerate() {
            for (before, after) in occurrences(name, line) {
                let strength = definition_strength(before, after, line);
                if strength > best.map(|b| b.1).unwrap_or(0) {
                    best = Some((first + offset as i32, strength));
                }
                if strength == 2 {
                    return best;
                }
            }
        }
        best
    }

    /// First line (from `first`) that has one of `words` as a definition, else as code.
    /// `upstream/Sources/DigUpKit/CodeExtractor.swift:320`
    pub fn first_line(words: &[&str], text: &str, first: i32) -> Option<i32> {
        let words: Vec<String> = words
            .iter()
            .filter(|w| w.len() >= 2)
            .map(|w| w.to_lowercase())
            .collect();
        if words.is_empty() {
            return None;
        }
        let mut first_code: Option<i32> = None;
        let mut first_any: Option<i32> = None;
        for (offset, line) in split_lines(text).into_iter().enumerate() {
            if !words.iter().any(|w| has_word(w, line)) {
                continue;
            }
            let trimmed = line.trim();
            if trimmed
                .split_whitespace()
                .take(4)
                .any(Self::defines_something)
            {
                return Some(first + offset as i32);
            }
            if first_code.is_none() && !COMMENT_STARTS.iter().any(|p| trimmed.starts_with(p)) {
                first_code = Some(offset as i32);
            }
            if first_any.is_none() {
                first_any = Some(offset as i32);
            }
        }
        first_code.or(first_any).map(|o| first + o)
    }
}

const CLOSERS: &[&str] = &[
    "end", "fi", "done", "esac", "@end", "#endif", "end;", "end)",
];
const DEFINERS: &[&str] = &[
    "def",
    "func",
    "fn",
    "fun",
    "function",
    "class",
    "struct",
    "enum",
    "protocol",
    "interface",
    "trait",
    "type",
    "typealias",
    "actor",
    "extension",
    "impl",
    "module",
    "namespace",
    "object",
    "record",
    "macro",
    "const",
    "let",
    "var",
    "val",
    "union",
    "mod",
    "sub",
    "@interface",
    "@implementation",
    "@protocol",
    "#define",
    "function*",
];
const USERS: &[&str] = &[
    "return", "await", "yield", "throw", "new", "else", "case", "print", "echo", "assert", "not",
    "and", "or", "in", "is", "do", "go", "defer", "try", "catch", "if", "while", "for", "typeof",
    "delete", "raise", "import", "from",
];
const COMMENT_STARTS: &[&str] = &["//", "#", "/*", "*", "--", "\"\"\"", "'''", "<!--", ";"];

fn definition_strength(before: &str, after: &str, line: &str) -> i32 {
    let before = before.trim();
    let after = after.trim();
    let previous = before.split_whitespace().next_back().unwrap_or("");
    if DEFINERS.contains(&previous) {
        return 2;
    }
    if before.starts_with("func (") && before.ends_with(')') {
        return 2;
    }
    if before.starts_with("- (") || before.starts_with("+ (") {
        return if after.starts_with(':')
            || after.is_empty()
            || after.starts_with('{')
            || after.starts_with(';')
        {
            2
        } else {
            0
        };
    }
    let last = before.chars().next_back();
    let c_style = after.starts_with('(')
        && !before.is_empty()
        && !USERS.contains(&previous)
        && !before.chars().any(|c| "=(,.!?".contains(c))
        && !before.contains("->")
        && last.is_some_and(|c| c.is_alphabetic() || c.is_numeric() || "*&>_]".contains(c));
    if !c_style {
        return 0;
    }
    if line.trim().ends_with(';') {
        1
    } else {
        2
    }
}

fn has_word(word: &str, line: &str) -> bool {
    let lower: Vec<char> = line.to_lowercase().chars().collect();
    let original: Vec<char> = line.chars().collect();
    let needle: Vec<char> = word.chars().collect();
    if needle.is_empty() || needle.len() > lower.len() {
        return false;
    }
    let mut i = 0usize;
    while i + needle.len() <= lower.len() {
        if lower[i..i + needle.len()] == needle[..] {
            let at_start = i == 0;
            let after_break = i > 0 && !lower[i - 1].is_alphabetic() && !lower[i - 1].is_numeric();
            let camel = original.get(i).is_some_and(|c| c.is_uppercase());
            if at_start || after_break || camel {
                return true;
            }
            i += needle.len();
        } else {
            i += 1;
        }
    }
    false
}

fn occurrences<'a>(name: &str, line: &'a str) -> Vec<(&'a str, &'a str)> {
    let lower_line = line.to_lowercase();
    let lower_name = name.to_lowercase();
    let mut found = Vec::new();
    let mut start = 0usize;
    let line_bytes = line.as_bytes();
    while let Some(rel) = lower_line[start..].find(&lower_name) {
        let i = start + rel;
        let j = i + lower_name.len();
        if !line.is_char_boundary(i) || !line.is_char_boundary(j) {
            start = i + 1;
            continue;
        }
        let before_ok = i == 0 || !is_name_byte(line_bytes[i - 1]);
        let after_ok = j == line.len() || !is_name_byte(line_bytes[j]);
        if before_ok && after_ok {
            found.push((&line[..i], &line[j..]));
        }
        start = j;
    }
    found
}

fn is_name_byte(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_' || b == b'$'
}

fn split_lines(text: &str) -> Vec<&str> {
    text.split('\n')
        .map(|l| l.strip_suffix('\r').unwrap_or(l))
        .collect()
}

fn line_count(text: &str) -> i32 {
    if text.is_empty() {
        return 0;
    }
    let n = text.bytes().filter(|b| *b == b'\n').count() as i32;
    if text.ends_with('\n') {
        n
    } else {
        n + 1
    }
}

fn dirs_home() -> String {
    std::env::var("HOME").unwrap_or_else(|_| "/".into())
}

fn is_ident_path(name: &str) -> bool {
    let mut rest = name;
    loop {
        let ident = match ident_prefix(rest) {
            Some(i) => i,
            None => return false,
        };
        rest = &rest[ident.len()..];
        if rest.is_empty() {
            return true;
        }
        for sep in ["::", "->", ".", "#"] {
            if let Some(next) = rest.strip_prefix(sep) {
                rest = next;
                break;
            }
            if sep == "#" {
                return false;
            }
        }
    }
}

fn ident_prefix(s: &str) -> Option<&str> {
    let mut chars = s.char_indices();
    let (_, first) = chars.next()?;
    if !(first.is_ascii_alphabetic() || first == '_' || first == '$') {
        return None;
    }
    let mut end = first.len_utf8();
    for (i, c) in chars {
        if c.is_ascii_alphanumeric() || c == '_' || c == '$' {
            end = i + c.len_utf8();
        } else {
            break;
        }
    }
    Some(&s[..end])
}

